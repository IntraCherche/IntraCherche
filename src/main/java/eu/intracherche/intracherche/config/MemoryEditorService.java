/**
 * The Memory tab: the Java heap (IC_HEAP_MB in jvm.conf, read by systemd), Solr's heap (SOLR_HEAP
 * in solr.in.sh) and the reservation floor (resources.reservedRamGb in application.yaml), shown
 * against the server's RAM so that a choice which would stop the application from starting is
 * refused here, not discovered in a crash loop.
 *
 * <p>Both heaps take effect at the next start of the application, which also restarts Solr.
 */
@Service
public class MemoryEditorService {

    private static final Logger log = LoggerFactory.getLogger(MemoryEditorService.class);

    static final String JVM_HEADER = """
            # Auto generated by the IntraCherche administration panel - do not edit by hand.
            # Fichier généré par le panneau d'administration d'IntraCherche - ne pas modifier à la main.
            """;
    static final String BEGIN = "# BEGIN IntraCherche heap";
    static final String END = "# END IntraCherche heap";
    private static final Pattern HEAP_LINE = Pattern.compile("^(\\s*SOLR_HEAP=)([\"']?)(\\d+)([mMgG]?)([\"']?)\\s*$");
    private static final Pattern JAVA_MEM_LINE = Pattern.compile("^\\s*SOLR_JAVA_MEM=.*$");
    private static final Pattern IC_HEAP_LINE = Pattern.compile("^\\s*IC_HEAP_MB=\"?(\\d+)\"?\\s*$");
    private static final DateTimeFormatter STAMP = DateTimeFormatter.ofPattern("yyyyMMdd-HHmmss-SSS");
    private static final int BACKUPS_KEPT = 10;

    /** How Solr's heap can be edited from here. */
    public enum SolrMode { BLOCK, LINE, READONLY, NOFILE }

    public record Input(Long appHeapMb, Long solrHeapMb, Integer reservedRamGb) {}

    public record MemoryView(long totalRamMb, long runningHeapMb, Long configuredHeapMb, boolean jvmConfAvailable,
                             String jvmConfPath, long solrHeapMb, SolrMode solrMode, String solrFile,
                             int reservedRamGb, boolean writable, String notWritableReason,
                             long recommendedHeapMb, long recommendedSolrMb) {}

    public record PreviewResult(ResourceValidator.Preview budget, List<Finding> findings) {}

    public record SaveResult(boolean saved, List<Finding> findings, List<String> backups, boolean restartRequired) {}

    private final ResourceValidator validator;
    private final ConfigCheckService checker;
    private final SettingsEditorService settings;
    private final Path solrInSh;

    @Autowired
    public MemoryEditorService(ResourceValidator validator, ConfigCheckService checker, SettingsEditorService settings) {
        this(validator, checker, settings, Path.of("solr", "bin", "solr.in.sh"));
    }

    MemoryEditorService(ResourceValidator validator, ConfigCheckService checker, SettingsEditorService settings, Path solrInSh) {
        this.validator = validator;
        this.checker = checker;
        this.settings = settings;
        this.solrInSh = solrInSh;
    }

    // ── Read ──────────────────────────────────────────────────────────────────

    public MemoryView read() {
        long total = validator.totalRamMb();
        Path jvm = jvmConf();
        Long configured = jvm == null ? null : readIcHeap(jvm);
        SolrMode mode = solrMode();
        int reserved = settings.read().settings().stream().filter(s -> s.key().equals("resources.reservedRamGb"))
                .map(s -> ((Number) s.value()).intValue()).findFirst().orElse(3);
        String reason = null;
        boolean writable = true;
        if (jvm == null) { writable = false; reason = "Aucun fichier de configuration externe : le tas Java ne peut pas être enregistré."; }
        else if (!ConfigFiles.canReplace(jvm)) {
            writable = false; reason = ConfigFiles.cannotReplaceReason(jvm);
        }
        return new MemoryView(total, validator.currentHeapMb(), configured, jvm != null,
                jvm == null ? null : jvm.toString(), validator.currentSolrHeapMb(), mode,
                Files.exists(solrInSh) ? solrInSh.toString() : null, reserved, writable, reason,
                clamp(total / 8, 1024, 8192), clamp(total / 16, 1024, 4096));
    }

    private static long clamp(long v, long lo, long hi) { return Math.max(lo, Math.min(hi, v)); }

    // ── Preview / validate ────────────────────────────────────────────────────

    public PreviewResult preview(Input in) {
        MemoryView cur = read();
        long heap = in.appHeapMb() != null ? in.appHeapMb() : cur.runningHeapMb();
        long solr = in.solrHeapMb() != null ? in.solrHeapMb() : cur.solrHeapMb();
        int reserved = in.reservedRamGb() != null ? in.reservedRamGb() : cur.reservedRamGb();
        List<Finding> f = new ArrayList<>();
        if (in.appHeapMb() != null) {
            if (heap < 512) f.add(err("appHeapMb", "Au moins 512 Mo."));
            if (heap > cur.totalRamMb() * 3 / 4) f.add(err("appHeapMb",
                    "Au plus les trois quarts de la mémoire du serveur (" + cur.totalRamMb() * 3 / 4 + " Mo)."));
        }
        if (in.solrHeapMb() != null) {
            if (solr < 512) f.add(err("solrHeapMb", "Au moins 512 Mo."));
            if (solr > cur.totalRamMb() / 2) f.add(err("solrHeapMb",
                    "Au plus la moitié de la mémoire du serveur : Solr garde son index dans le cache du système, pas dans son tas."));
            if (cur.solrMode() == SolrMode.READONLY || cur.solrMode() == SolrMode.NOFILE) {
                f.add(err("solrHeapMb", cur.solrMode() == SolrMode.NOFILE
                        ? "Le fichier solr.in.sh est introuvable."
                        : "solr.in.sh règle la mémoire par SOLR_JAVA_MEM : modifiez-la à la main ou remplacez-la par SOLR_HEAP."));
            }
        }
        if (in.reservedRamGb() != null && (reserved < 1 || reserved > 1024)) f.add(err("reservedRamGb", "Entre 1 et 1024 Go."));
        ResourceValidator.Preview b = validator.preview(heap, solr, reserved);
        if (b.servicesKnown() && b.minimumMb() > b.budgetMb()) {
            f.add(err("budget", "Avec ces valeurs, même un seul processus par service ne tient pas en mémoire ("
                    + gb(b.minimumMb()) + " Go nécessaires, " + gb(Math.max(0, b.budgetMb())) + " Go disponibles) : "
                    + "l'application refuserait de démarrer. Réduisez un tas, désactivez Sherlock ou ajoutez de la mémoire."));
        } else if (b.servicesKnown() && b.neededMb() > b.budgetMb()) {
            f.add(new Finding(ConfigCheckService.WARNING, "mémoire", "budget",
                    "Les services actuels (" + gb(b.neededMb()) + " Go) ne tiendraient plus : au prochain démarrage, "
                            + "l'application réduira d'elle-même leur nombre de processus."));
        }
        return new PreviewResult(b, f);
    }

    private static Finding err(String where, String msg) { return new Finding(ConfigCheckService.ERROR, "mémoire", where, msg); }
    private static String gb(long mb) { return String.format("%.1f", mb / 1024.0); }

    // ── Save ──────────────────────────────────────────────────────────────────

    public synchronized SaveResult save(Input in, Collection<String> askerAuthorities) throws IOException {
        PreviewResult p = preview(in);
        MemoryView cur = read();
        List<Finding> findings = new ArrayList<>(p.findings());
        if (in.appHeapMb() != null && !cur.writable()) findings.add(err("appHeapMb", cur.notWritableReason()));
        if (in.solrHeapMb() != null && cur.solrMode() != SolrMode.READONLY && cur.solrMode() != SolrMode.NOFILE
                && !ConfigFiles.canReplace(solrInSh)) {
            findings.add(err("solrHeapMb", ConfigFiles.cannotReplaceReason(solrInSh)));
        }
        if (findings.stream().anyMatch(f -> ConfigCheckService.ERROR.equals(f.severity()))) {
            return new SaveResult(false, findings, List.of(), false);
        }
        List<String> backups = new ArrayList<>();
        if (in.reservedRamGb() != null && in.reservedRamGb() != cur.reservedRamGb()) {
            SettingsEditorService.SaveResult r = settings.save(Map.of("resources.reservedRamGb", in.reservedRamGb()), askerAuthorities);
            findings.addAll(r.findings());
            if (!r.saved()) return new SaveResult(false, findings, backups, false);
            backups.add(r.backup());
        }
        if (in.appHeapMb() != null && !in.appHeapMb().equals(cur.configuredHeapMb())) {
            backups.add(writeJvmConf(jvmConf(), in.appHeapMb()));
        }
        if (in.solrHeapMb() != null && in.solrHeapMb() != cur.solrHeapMb()) {
            backups.add(writeSolrHeap(in.solrHeapMb()));
        }
        backups.removeIf(b -> b == null);
        return new SaveResult(true, findings, backups, true);
    }

    String writeJvmConf(Path file, long heapMb) throws IOException {
        List<String> kept = new ArrayList<>();
        if (Files.isRegularFile(file)) {
            for (String line : Files.readAllLines(file, StandardCharsets.UTF_8)) {
                String t = line.trim();
                if (t.isEmpty() || t.startsWith("#") || IC_HEAP_LINE.matcher(line).matches()) continue;
                kept.add(line);
            }
        }
        StringBuilder sb = new StringBuilder(JVM_HEADER).append("IC_HEAP_MB=").append(heapMb).append('\n');
        kept.forEach(l -> sb.append(l).append('\n'));
        String backup = backupAndWrite(file, sb.toString());
        log.info("jvm.conf rewritten from the administration panel: IC_HEAP_MB={}", heapMb);
        return backup;
    }

    String writeSolrHeap(long heapMb) throws IOException {
        List<String> lines = Files.readAllLines(solrInSh, StandardCharsets.UTF_8);
        List<String> out = new ArrayList<>();
        boolean inBlock = false;
        boolean replacedInPlace = false;
        for (String line : lines) {
            if (line.startsWith(BEGIN)) { inBlock = true; continue; }
            if (inBlock) { if (line.startsWith(END)) inBlock = false; continue; }
            Matcher m = HEAP_LINE.matcher(line);
            if (m.matches()) {   // the admin's own line: edit it where it stands
                out.add(m.group(1) + m.group(2) + heapMb + "m" + m.group(5));
                replacedInPlace = true;
            } else out.add(line);
        }
        if (!replacedInPlace) {
            out.add(BEGIN + " (written by the administration panel; delete this block and set your own SOLR_HEAP to override)");
            out.add("SOLR_HEAP=\"" + heapMb + "m\"");
            out.add(END);
        }
        String backup = backupAndWrite(solrInSh, String.join("\n", out) + "\n");
        log.info("solr.in.sh rewritten from the administration panel: SOLR_HEAP={}m", heapMb);
        return backup;
    }

    private String backupAndWrite(Path file, String content) throws IOException {
        return ConfigFiles.replace(file, content);
    }

    // ── Helpers ───────────────────────────────────────────────────────────────

    private Path jvmConf() {
        Path app = checker.locateApplicationFile();
        return app == null ? null : app.toAbsolutePath().resolveSibling("jvm.conf");
    }

    private static Long readIcHeap(Path file) {
        try {
            for (String line : Files.readAllLines(file, StandardCharsets.UTF_8)) {
                Matcher m = IC_HEAP_LINE.matcher(line);
                if (m.matches()) return Long.parseLong(m.group(1));
            }
        } catch (IOException | RuntimeException ignored) { /* no such file: the unit's default applies */ }
        return null;
    }

    private SolrMode solrMode() {
        if (!Files.isRegularFile(solrInSh)) return SolrMode.NOFILE;
        try {
            boolean inBlock = false, line = false, javaMem = false;
            for (String l : Files.readAllLines(solrInSh, StandardCharsets.UTF_8)) {
                if (l.startsWith(BEGIN)) { inBlock = true; continue; }
                if (inBlock) { if (l.startsWith(END)) inBlock = false; continue; }
                if (HEAP_LINE.matcher(l).matches()) line = true;
                if (JAVA_MEM_LINE.matcher(l).matches()) javaMem = true;
            }
            if (line) return SolrMode.LINE;
            if (javaMem) return SolrMode.READONLY;
            return SolrMode.BLOCK;
        } catch (IOException e) {
            return SolrMode.NOFILE;
        }
    }
}
