/**
 * Reads and writes indexes.yaml for the admin panel's Indexes tab.
 *
 * <p>The file is regenerated whole, with a header saying so: comments cannot survive a rewrite,
 * and the explanations live in the panel. A candidate goes through the same checks as a file
 * edited by hand ({@link ConfigCheckService}), plus two live ones (the AD groups exist, a share
 * can be opened) before anything touches the disk. The previous file is kept as a backup.
 *
 * <p>Passwords never leave the server: the panel gets "a password is set", and a blank password
 * sent back means "keep the stored one".
 */
@Service
public class IndexesEditorService {

    private static final Logger log = LoggerFactory.getLogger(IndexesEditorService.class);

    static final String HEADER = """
            # Auto generated by the IntraCherche administration panel - do not edit by hand.
            # Fichier généré par le panneau d'administration d'IntraCherche - ne pas modifier à la main.
            # Settings are explained in the panel (Administration > Configuration).
            """;
    private static final int BACKUPS_KEPT = 10;
    private static final DateTimeFormatter STAMP = DateTimeFormatter.ofPattern("yyyyMMdd-HHmmss-SSS");

    public record DirDto(String smbServer, String smbShare, String smbUser, String smbDomain,
                         String smbPassword, boolean passwordSet) {}

    public record IndexDto(String coreName, String status, boolean confirmDelete, boolean ocr,
                           List<String> allowedExtensions, boolean visibleToAll, List<String> visibleToGroups,
                           List<DirDto> indexedDirs) {}

    public record EditableConfig(String file, boolean writable, String notWritableReason,
                                 List<IndexDto> indexes, List<String> defaultExtensions,
                                 List<String> ignoredKeys) {}

    public record SaveResult(boolean saved, List<Finding> findings, String backup, boolean restartRequired) {}

    public record ShareTest(boolean ok, String message) {}

    private final Environment env;
    private final ConfigCheckService checker;
    private final SecurityService securityService;

    public IndexesEditorService(Environment env, ConfigCheckService checker, SecurityService securityService) {
        this.env = env;
        this.checker = checker;
        this.securityService = securityService;
    }

    // ── Read ──────────────────────────────────────────────────────────────────

    public EditableConfig read() {
        Path file = file();
        List<String> ignored = new ArrayList<>();
        List<IndexDto> indexes = new ArrayList<>();
        Map<String, Object> root = readRoot(file);
        if (root.get("indexes") instanceof List<?> items) {
            for (Object item : items) {
                if (!(item instanceof Map<?, ?>)) continue;
                Map<String, Object> m = map(item);
                String core = str(m.get("coreName"));
                m.keySet().stream().filter(k -> !Set.of("coreName", "status", "confirmDelete", "ocr",
                        "allowedExtensions", "visibleToGroups", "indexedDirs").contains(k))
                        .forEach(k -> ignored.add(core + " › " + k));
                List<DirDto> dirs = new ArrayList<>();
                if (m.get("indexedDirs") instanceof List<?> dl) {
                    for (Object d : dl) {
                        Map<String, Object> dm = map(d);
                        dm.keySet().stream().filter(k -> !Set.of("mountType", "smbServer", "smbShare", "smbUser",
                                "smbPassword", "smbDomain").contains(k)).forEach(k -> ignored.add(core + " › " + k));
                        dirs.add(new DirDto(str(dm.get("smbServer")), str(dm.get("smbShare")), str(dm.get("smbUser")),
                                str(dm.get("smbDomain")), null, !str(dm.get("smbPassword")).isEmpty()));
                    }
                }
                boolean all = false;
                List<String> groups = new ArrayList<>();
                Object v = m.get("visibleToGroups");
                if (v instanceof List<?> l) l.forEach(g -> groups.add(str(g)));
                else if (v != null) groups.add(str(v));
                if (groups.size() == 1 && groups.get(0).equalsIgnoreCase("ALL")) { all = true; groups.clear(); }
                List<String> exts = null;
                if (m.get("allowedExtensions") instanceof List<?> el) {
                    exts = new ArrayList<>();
                    for (Object e : el) exts.add(str(e));
                }
                indexes.add(new IndexDto(core, str(m.getOrDefault("status", "ACTIVE")).toUpperCase(Locale.ROOT),
                        Boolean.TRUE.equals(m.get("confirmDelete")), !Boolean.FALSE.equals(m.get("ocr")),
                        exts, all, groups, dirs));
            }
        }
        String reason = null;
        boolean writable = ConfigFiles.canReplace(file);
        if (!writable) reason = ConfigFiles.cannotReplaceReason(file);
        return new EditableConfig(file.toString(), writable, reason, indexes,
                IndexConfig.DEFAULT_ALLOWED_EXTENSIONS.stream().sorted().toList(), ignored);
    }

    // ── Validate / save ───────────────────────────────────────────────────────

    public List<Finding> validate(List<IndexDto> candidate) {
        List<Finding> findings = new ArrayList<>();
        Map<String, Object> root = toRoot(candidate, findings);
        checker.checkIndexesRoot(root, findings);
        checkGroups(candidate, findings);
        // New entries: their core name becomes a Solr core name.
        Set<String> existing = new LinkedHashSet<>();
        read().indexes().forEach(i -> existing.add(i.coreName()));
        for (IndexDto i : candidate) {
            if (i.coreName() != null && !existing.contains(i.coreName())
                    && !i.coreName().matches("[A-Za-z0-9][A-Za-z0-9_-]*")) {
                findings.add(new Finding(ConfigCheckService.ERROR, "indexes.yaml", i.coreName(),
                        "Nom d'index invalide : lettres, chiffres, « _ » et « - » seulement, sans espace ni accent."));
            }
        }
        // An index present in the file must not vanish: its Solr core would be orphaned.
        for (String name : existing) {
            if (candidate.stream().noneMatch(i -> name.equals(i.coreName()))) {
                findings.add(new Finding(ConfigCheckService.ERROR, "indexes.yaml", name,
                        "Un index existant ne peut pas être retiré de la liste : passez son statut à « delete » "
                                + "(avec confirmation) pour le supprimer proprement."));
            }
        }
        return findings;
    }

    public synchronized SaveResult save(List<IndexDto> candidate) throws IOException {
        EditableConfig current = read();
        if (!current.writable()) {
            return new SaveResult(false, List.of(new Finding(ConfigCheckService.ERROR, "indexes.yaml",
                    current.file(), current.notWritableReason())), null, false);
        }
        List<Finding> findings = validate(candidate);
        if (findings.stream().anyMatch(f -> ConfigCheckService.ERROR.equals(f.severity()))) {
            return new SaveResult(false, findings, null, false);
        }
        Map<String, Object> root = toRoot(candidate, new ArrayList<>());
        String yaml = HEADER + "\n" + new Dump(DumpSettings.builder()
                .setDefaultFlowStyle(FlowStyle.BLOCK).setIndent(2).setIndicatorIndent(2)
                .setIndentWithIndicator(true).build()).dumpToString(root);
        // The text must read back as what was checked, or nothing is written.
        new Load(LoadSettings.builder().setAllowDuplicateKeys(false).build()).loadFromString(yaml);

        String backup = ConfigFiles.replace(file(), yaml);
        log.info("indexes.yaml rewritten from the administration panel ({} indexes), backup {}", candidate.size(), backup);
        return new SaveResult(true, findings, backup, true);
    }

    // ── Live checks ───────────────────────────────────────────────────────────

    private void checkGroups(List<IndexDto> candidate, List<Finding> findings) {
        Set<String> checked = new LinkedHashSet<>();
        for (IndexDto i : candidate) {
            if (i.visibleToAll() || i.visibleToGroups() == null) continue;
            for (String g : i.visibleToGroups()) {
                if (g == null || g.isBlank() || !checked.add(g)) continue;
                try {
                    List<DirectoryGroup> found = securityService.findBySamAccountName(g);
                    if (found.isEmpty()) {
                        findings.add(new Finding(ConfigCheckService.ERROR, "indexes.yaml", i.coreName() + " › visibleToGroups",
                                "Le groupe « " + g + " » n'existe pas dans l'annuaire (nom de groupe antérieur à Windows 2000 attendu)."));
                    } else if (found.size() > 1 || !found.get(0).group()) {
                        findings.add(new Finding(ConfigCheckService.ERROR, "indexes.yaml", i.coreName() + " › visibleToGroups",
                                "« " + g + " » ne désigne pas un groupe unique de l'annuaire."));
                    }
                } catch (RuntimeException e) {
                    findings.add(new Finding(ConfigCheckService.WARNING, "indexes.yaml", i.coreName() + " › visibleToGroups",
                            "L'annuaire n'a pas pu être interrogé : le groupe « " + g + " » n'est pas vérifié."));
                }
            }
        }
    }

    /** Opens the share with the given credentials and lists its root. A blank password uses the stored one. */
    public ShareTest testShare(String coreName, DirDto dir) {
        if (dir == null || blank(dir.smbServer()) || blank(dir.smbShare())) {
            return new ShareTest(false, "Serveur et partage sont obligatoires.");
        }
        String password = dir.smbPassword();
        if (blank(password)) password = storedPassword(coreName, dir);
        if (blank(password)) return new ShareTest(false, "Mot de passe manquant.");
        IndexedDirConfig cfg = new IndexedDirConfig();
        cfg.setMountType(MountType.SMB);
        cfg.setSmbServer(dir.smbServer().trim());
        cfg.setSmbShare(dir.smbShare().trim());
        cfg.setSmbUser(dir.smbUser());
        cfg.setSmbPassword(password);
        cfg.setSmbDomain(blank(dir.smbDomain()) ? null : dir.smbDomain().trim());
        try (SmbClientManager smb = new SmbClientManager()) {
            smb.registerConfig(cfg);
            DiskShare share = smb.getShare(cfg.getSmbServer(), cfg.getSmbShare());
            int n = share.list("").size();
            return new ShareTest(true, "Partage accessible (" + n + " éléments à la racine).");
        } catch (Exception e) {
            Throwable root = e;
            while (root.getCause() != null) root = root.getCause();
            String why = root.getMessage() == null ? root.getClass().getSimpleName() : root.getMessage();
            return new ShareTest(false, "Échec : " + why);
        }
    }

    // ── Building the file ─────────────────────────────────────────────────────

    private Map<String, Object> toRoot(List<IndexDto> candidate, List<Finding> findings) {
        Map<String, Map<String, String>> stored = storedPasswords();
        List<Object> list = new ArrayList<>();
        for (IndexDto i : candidate) {
            Map<String, Object> m = new LinkedHashMap<>();
            m.put("coreName", i.coreName() == null ? "" : i.coreName().trim());
            m.put("status", (i.status() == null ? "ACTIVE" : i.status()).toUpperCase(Locale.ROOT));
            if (i.confirmDelete()) m.put("confirmDelete", true);
            if (i.visibleToAll()) m.put("visibleToGroups", "ALL");
            else m.put("visibleToGroups", i.visibleToGroups() == null ? null : i.visibleToGroups().stream()
                    .filter(g -> g != null && !g.isBlank()).map(String::trim).toList());
            m.put("ocr", i.ocr());
            if (i.allowedExtensions() != null) {
                m.put("allowedExtensions", i.allowedExtensions().stream().filter(e -> e != null && !e.isBlank())
                        .map(e -> e.trim().toLowerCase(Locale.ROOT)).toList());
            }
            List<Object> dirs = new ArrayList<>();
            if (i.indexedDirs() != null) {
                for (DirDto d : i.indexedDirs()) {
                    Map<String, Object> dm = new LinkedHashMap<>();
                    dm.put("mountType", "SMB");
                    dm.put("smbServer", trim(d.smbServer()));
                    dm.put("smbShare", trim(d.smbShare()));
                    dm.put("smbUser", trim(d.smbUser()));
                    String pwd = d.smbPassword();
                    if (blank(pwd)) {
                        pwd = stored.getOrDefault(i.coreName(), Map.of()).get(key(d));
                        if (pwd == null) pwd = anyStored(stored, d);
                    }
                    dm.put("smbPassword", pwd == null ? "" : pwd);
                    if (!blank(d.smbDomain())) dm.put("smbDomain", d.smbDomain().trim());
                    dirs.add(dm);
                }
            }
            m.put("indexedDirs", dirs);
            list.add(m);
        }
        Map<String, Object> root = new LinkedHashMap<>();
        root.put("indexes", list);
        return root;
    }

    private String storedPassword(String coreName, DirDto d) {
        Map<String, Map<String, String>> stored = storedPasswords();
        String p = stored.getOrDefault(coreName, Map.of()).get(key(d));
        return p != null ? p : anyStored(stored, d);
    }

    private static String anyStored(Map<String, Map<String, String>> stored, DirDto d) {
        for (Map<String, String> m : stored.values()) {
            String p = m.get(key(d));
            if (p != null) return p;
        }
        return null;
    }

    private static String key(DirDto d) {
        return (trim(d.smbServer()) + "|" + trim(d.smbShare()) + "|" + trim(d.smbUser())).toLowerCase(Locale.ROOT);
    }

    /** coreName → (server|share|user → password) from the file now on disk. */
    private Map<String, Map<String, String>> storedPasswords() {
        Map<String, Map<String, String>> out = new LinkedHashMap<>();
        if (readRoot(file()).get("indexes") instanceof List<?> items) {
            for (Object item : items) {
                Map<String, Object> m = map(item);
                Map<String, String> byDir = new LinkedHashMap<>();
                if (m.get("indexedDirs") instanceof List<?> dl) {
                    for (Object d : dl) {
                        Map<String, Object> dm = map(d);
                        byDir.put((str(dm.get("smbServer")) + "|" + str(dm.get("smbShare")) + "|" + str(dm.get("smbUser")))
                                .toLowerCase(Locale.ROOT), str(dm.get("smbPassword")));
                    }
                }
                out.put(str(m.get("coreName")), byDir);
            }
        }
        return out;
    }

    // ── Helpers ───────────────────────────────────────────────────────────────

    private Path file() {
        return Path.of(env.getRequiredProperty("indexing-config.indexesConfigPath"));
    }

    private Map<String, Object> readRoot(Path file) {
        if (!Files.isRegularFile(file)) return Map.of();
        try (Reader r = Files.newBufferedReader(file, StandardCharsets.UTF_8)) {
            return map(new Load(LoadSettings.builder().build()).loadFromReader(r));
        } catch (IOException | RuntimeException e) {
            return Map.of();
        }
    }

    private static Map<String, Object> map(Object o) {
        Map<String, Object> out = new LinkedHashMap<>();
        if (o instanceof Map<?, ?> m) m.forEach((k, v) -> out.put(String.valueOf(k), v));
        return out;
    }

    private static String str(Object o) { return o == null ? "" : String.valueOf(o); }
    private static String trim(String s) { return s == null ? "" : s.trim(); }
    private static boolean blank(String s) { return s == null || s.isBlank(); }
}
